"""Recording-feedback earcons through GStreamer.

Plays short bundled WAV cues (`quoth/sounds/`) for users without the on-screen pill.
Each cue is a persistent, prerolled `playbin` held while sound feedback is on, since a
fresh one per press costs ~80 ms against ~1 ms. A prerolled cue holds its PipeWire
output stream open, so the app calls `prewarm()` only while sound feedback is enabled
and `shutdown()` when it is switched off; otherwise a cue is built on first use.

Best effort: `play()` returns at once and a missing file or element is logged, never
raised, so feedback never breaks recording.

The cues are generated by `scripts/generate_sounds.py`; change and rerun it rather than
editing the WAVs.
"""

from __future__ import annotations

from pathlib import Path

import gi

gi.require_version("Gst", "1.0")
from gi.repository import Gst
from loguru import logger

_SOUNDS_DIR = Path(__file__).resolve().parent / "sounds"

# The cues the app uses; `prewarm()` builds and prerolls them together.
_DEFAULT_CUES = ("start", "stop")


class SoundPlayer:
    """A player for the named earcons ("start", "stop") in `quoth/sounds/*.wav`.

    EOS returns a cue to PAUSED, and a playback error evicts it so the next `play()`
    rebuilds it.
    """

    def __init__(self) -> None:
        self._cues: dict[str, Gst.Element] = {}

    def _get_or_make(self, name: str) -> Gst.Element | None:
        """Return the persistent prerolled playbin for `name`, building it on first use.

        None, logged, when the WAV or the `playbin` element is unavailable; the caller
        then does nothing, keeping feedback best effort.
        """
        cached = self._cues.get(name)
        if cached is not None:
            return cached
        path = _SOUNDS_DIR / f"{name}.wav"
        if not path.is_file():
            logger.warning("Sound cue '{}' not found at {}", name, path)
            return None
        playbin = Gst.ElementFactory.make("playbin", None)
        if playbin is None:
            logger.warning("Sound cue unavailable: 'playbin' element missing")
            return None
        playbin.set_property("uri", path.as_uri())
        bus = playbin.get_bus()
        bus.add_signal_watch()
        bus.connect("message", self._on_message, name)
        # Preroll: PAUSED plugs the decoder and opens the audio sink now, so the later
        # PLAYING transition is immediate. Async: we don't block the main thread on it.
        playbin.set_state(Gst.State.PAUSED)
        self._cues[name] = playbin
        logger.debug("Sound cue prerolled: {}", name)
        return playbin

    def prewarm(self, names: tuple[str, ...] = _DEFAULT_CUES) -> None:
        """Preroll `names` now so the first earcon is as fast as every later one."""
        for name in names:
            self._get_or_make(name)

    def play(self, name: str, volume: int = 100) -> None:
        """Play a named earcon at the given volume (0-100).

        A cue still audible from a recent press is left to finish, not restarted.
        """
        playbin = self._get_or_make(name)
        if playbin is None:
            return
        playbin.set_property("volume", max(0.0, min(1.0, volume / 100.0)))
        _, state, _ = playbin.get_state(0)
        if state == Gst.State.PLAYING:
            # Restarting a playing cue needs a flushing seek mid-playback, which
            # clicks; the cues are short, so let this one finish.
            logger.debug("Sound cue '{}' still playing; skipping retrigger", name)
            return
        if state == Gst.State.PAUSED:
            # Seeking a paused pipeline is click-free, and the flush clears any post-EOS
            # state so the replay starts from the beginning.
            playbin.seek_simple(
                Gst.Format.TIME, Gst.SeekFlags.FLUSH | Gst.SeekFlags.KEY_UNIT, 0
            )
        playbin.set_state(Gst.State.PLAYING)
        logger.debug("Playing sound cue: {} (volume {}%)", name, volume)

    def _on_message(self, bus: Gst.Bus, message: Gst.Message, name: str) -> None:
        if message.type == Gst.MessageType.EOS:
            # Rewind-ready: back to PAUSED, kept cached and prerolled for the next play.
            playbin = self._cues.get(name)
            if playbin is not None:
                playbin.set_state(Gst.State.PAUSED)
            return
        if message.type == Gst.MessageType.ERROR:
            err, _ = message.parse_error()
            logger.warning("Sound cue playback error: {}", err.message)
            # Evict the broken cue so the next play() rebuilds it from scratch.
            self._teardown_cue(name)
        elif message.type == Gst.MessageType.WARNING:
            # Non-fatal (underrun, sink latency): keep the cue, just surface it.
            warn, _ = message.parse_warning()
            logger.warning("Sound cue playback warning: {}", warn.message)

    def _teardown_cue(self, name: str) -> None:
        playbin = self._cues.pop(name, None)
        if playbin is None:
            return
        bus = playbin.get_bus()
        if bus is not None:
            bus.remove_signal_watch()
        playbin.set_state(Gst.State.NULL)

    def shutdown(self) -> None:
        """Tear down every prerolled cue, closing its output stream."""
        for name in list(self._cues):
            self._teardown_cue(name)
